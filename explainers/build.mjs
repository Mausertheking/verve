/**
 * Renders an explainer video for every lesson and drill, in every language
 * that has text, from /content.
 *
 *   node explainers/build.mjs                 # everything (incremental)
 *   node explainers/build.mjs rules-offside-01 drill:gk-angles-01
 *   node explainers/build.mjs --force         # ignore the cache
 *   node explainers/build.mjs --html-only     # write compositions, don't render
 *   node explainers/build.mjs --shard 1/3     # run one of N parallel workers
 *
 * Two kinds of composition:
 *   - bespoke projects (explainers/<id>/index.html) with hand-built figure
 *     animation, filled through composition variables;
 *   - everything else is generated by lesson-template.mjs.
 *
 * Output: assets/videos/{lessons,drills}/<id>.<lang>.mp4 (960×540 H.264, no
 * audio, faststart) and a regenerated src/content/videos.ts registry.
 * A language is rendered only when the item has its own text in it.
 * Renders are cached by a hash of their inputs (.work/cache.json).
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync, copyFileSync, readdirSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

import { compose, plain } from './lesson-template.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const CONTENT = join(ROOT, 'content');
const OUT = join(ROOT, 'assets', 'videos');
const WORK = join(HERE, '.work');
const HF = 'hyperframes@0.8.150';
const LANGS = ['az', 'ru', 'en'];

const read = (p) => JSON.parse(readFileSync(p, 'utf8'));
const lessons = ['rules', 'positions', 'goalkeeper'].flatMap((f) => read(join(CONTENT, 'lessons', `${f}.json`)));
const drills = read(join(CONTENT, 'drills.json'));
const tracks = read(join(CONTENT, 'tracks.json'));
const ui = Object.fromEntries(LANGS.map((L) => [L, read(join(ROOT, 'src', 'i18n', 'locales', `${L}.json`))]));
const upper = (s, L) => s.toLocaleUpperCase(L === 'az' ? 'az' : L);
const has = (o, L) => !!(o && o[L] && o[L].length);

const BESPOKE = ['gk-stance-01', 'gk-catching-01', 'pos-goalkeeper-01', 'rules-referee-01']
  .filter((id) => existsSync(join(HERE, id, 'index.html')));

// ---------------------------------------------------------------------------
// Payloads
// ---------------------------------------------------------------------------
function lessonKicker(l, L) {
  const track = tracks.find((t) => t.id === l.trackId);
  const siblings = lessons.filter((x) => x.trackId === l.trackId).sort((a, b) => a.order - b.order);
  const n = siblings.findIndex((x) => x.id === l.id) + 1;
  return `${upper(track.title[L], L)} · ${upper(ui[L].lessonOf.replace('{{n}}', n).replace('{{total}}', siblings.length), L)}`;
}

function lessonPayload(l, L) {
  if (!has(l.body, L) || !has(l.takeaways, L) || !has(l.title, L)) return null;
  const sections = [];
  let cur = { paras: [] };
  for (const para of l.body[L]) {
    if (para.startsWith('## ')) {
      if (cur.paras.length) sections.push(cur);
      cur = { heading: para.slice(3), paras: [] };
    } else cur.paras.push(para);
  }
  if (cur.paras.length) sections.push(cur);
  const d = l.diagram;
  return {
    lang: L,
    kicker: lessonKicker(l, L),
    title: l.title[L],
    subtitle: l.video?.caption?.[L] || '',
    sections,
    diagram: d && (d.paths?.length || d.markers?.length) ? {
      data: d,
      label: ui[L].howItLooks,
      beats: (d.beats ?? []).map((b) => b[L] || b.az),
      caption: d.caption ? d.caption[L] || d.caption.az : '',
    } : null,
    lists: [{ heading: ui[L].takeaways, items: l.takeaways[L], mark: 'n' }],
    close: { line: l.title[L], source: l.source ? `${ui[L].source}: ${l.source}` : '' },
  };
}

const SPACE_KEY = { bedroom: 'spaceBedroom', yard: 'spaceYard', 'half-pitch': 'spaceHalfPitch' };
function drillPayload(d, L) {
  if (!has(d.steps, L) || !has(d.whatGoodLooksLike, L) || !has(d.title, L)) return null;
  const g = d.diagram;
  return {
    lang: L,
    kicker: upper(`${ui[L].trainKicker} · ${d.minutes} ${ui[L].min}`, L),
    title: d.title[L],
    subtitle: `${ui[L][SPACE_KEY[d.space]]} · ${ui[L][d.group === 'solo' ? 'grpSolo' : 'grpGroup']}`,
    sections: d.why && d.why[L] ? [{ heading: ui[L].whyDrill, paras: [d.why[L]] }] : [],
    diagram: g ? {
      data: g,
      label: ui[L].howItLooks,
      beats: (g.beats ?? []).map((b) => b[L] || b.az),
      caption: g.caption ? g.caption[L] || g.caption.az : '',
    } : null,
    lists: [
      { heading: ui[L].steps, items: d.steps[L], mark: 'n' },
      { heading: ui[L].whatGood, items: d.whatGoodLooksLike[L], mark: 'check' },
    ],
    close: { line: d.title[L] },
  };
}

// Variables for the bespoke compositions.
function bespokeVars(id, L) {
  const l = lessons.find((x) => x.id === id);
  if (!has(l.body, L) || !has(l.takeaways, L)) return null;
  const body = l.body[L].filter((p) => !p.startsWith('## ')).map(plain);
  const tk = l.takeaways[L].map(plain);
  const base = { kicker: lessonKicker(l, L), title: l.title[L], caption: l.video?.caption?.[L] || l.title[L] };
  if (id === 'gk-stance-01') return { ...base, t1: tk[0], t2: tk[1], t3: tk[2], quote: body[body.length - 1] };
  if (id === 'gk-catching-01') {
    return { ...base, b1: body[1], b2: body[2], b3: body[3], t1: tk[0], t2: tk[1], t3: tk[2] };
  }
  if (id === 'pos-goalkeeper-01') return { ...base, b1: body[0], b2: [body[1], body[2], body[3]].join(' '), b3: body[body.length - 1], t1: tk[0], t2: tk[1], t3: tk[2] };
  if (id === 'rules-referee-01') return { ...base, source: `${ui[L].source}: ${l.source}`, ...Object.fromEntries(['advantage', 'direct', 'indirect', 'penalty', 'corner', 'goalkick', 'yellow', 'red'].map((k) => [k, refLabel(k, L)])) };
  return null;
}
const REF = {
  advantage: { az: 'Üstünlük — oyun davam edir', ru: 'Преимущество — игра продолжается', en: 'Advantage — play on' },
  direct: { az: 'Birbaşa cərimə zərbəsi', ru: 'Прямой штрафной', en: 'Direct free kick' },
  indirect: { az: 'Dolayı cərimə zərbəsi', ru: 'Свободный удар', en: 'Indirect free kick' },
  penalty: { az: 'Penalti', ru: 'Пенальти', en: 'Penalty kick' },
  corner: { az: 'Künc zərbəsi', ru: 'Угловой', en: 'Corner kick' },
  goalkick: { az: 'Qapı zərbəsi', ru: 'Удар от ворот', en: 'Goal kick' },
  yellow: { az: 'Sarı vərəqə — xəbərdarlıq', ru: 'Жёлтая — предупреждение', en: 'Yellow card — caution' },
  red: { az: 'Qırmızı vərəqə — meydandan kənar', ru: 'Красная — удаление', en: 'Red card — sent off' },
};
const refLabel = (k, L) => REF[k][L];

// ---------------------------------------------------------------------------
// Jobs
// ---------------------------------------------------------------------------
const args = process.argv.slice(2);
const force = args.includes('--force');
const htmlOnly = args.includes('--html-only');
const shardArg = args.includes('--shard') ? args[args.indexOf('--shard') + 1] : null;
const [shardI, shardN] = shardArg ? shardArg.split('/').map(Number) : [1, 1];
const only = args.filter((a, i) => !a.startsWith('--') && args[i - 1] !== '--shard');

const jobs = [];
for (const l of lessons) {
  for (const L of LANGS) {
    const key = `lesson:${l.id}`;
    if (only.length && !only.includes(l.id) && !only.includes(key)) continue;
    if (BESPOKE.includes(l.id)) {
      const vars = bespokeVars(l.id, L);
      if (vars) jobs.push({ key, id: l.id, L, kind: 'lessons', bespoke: true, vars });
    } else {
      const p = lessonPayload(l, L);
      if (p) jobs.push({ key, id: l.id, L, kind: 'lessons', payload: p });
    }
  }
}
for (const d of drills) {
  for (const L of LANGS) {
    const key = `drill:${d.id}`;
    if (only.length && !only.includes(key)) continue;
    const p = drillPayload(d, L);
    if (p) jobs.push({ key, id: d.id, L, kind: 'drills', payload: p });
  }
}

mkdirSync(WORK, { recursive: true });
const cachePath = join(WORK, 'cache.json');
const cache = existsSync(cachePath) ? read(cachePath) : {};
const templateHash = createHash('sha1').update(readFileSync(join(HERE, 'lesson-template.mjs'))).digest('hex');

let done = 0;
for (const [ji, job] of jobs.entries()) {
  if (ji % shardN !== shardI - 1) continue;
  const target = join(OUT, job.kind, `${job.id}.${job.L}.mp4`);
  mkdirSync(dirname(target), { recursive: true });
  const dir = job.bespoke ? join(HERE, job.id) : join(WORK, `${job.kind}-${job.id}-${job.L}`);
  let hashInput;
  if (job.bespoke) {
    writeFileSync(join(dir, `vars.${job.L}.json`), JSON.stringify(job.vars, null, 2) + '\n');
    hashInput = readFileSync(join(dir, 'index.html'), 'utf8') + JSON.stringify(job.vars);
  } else {
    const { html } = compose(job.payload);
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, 'index.html'), html);
    if (!existsSync(join(dir, 'hyperframes.json'))) {
      writeFileSync(join(dir, 'hyperframes.json'), JSON.stringify({ authoringSkill: 'general-video' }, null, 2));
      writeFileSync(join(dir, 'meta.json'), JSON.stringify({ id: `${job.id}-${job.L}`, name: `${job.id}-${job.L}` }));
    }
    hashInput = html + templateHash;
  }
  const hash = createHash('sha1').update(hashInput).digest('hex');
  const cacheKey = `${job.kind}/${job.id}.${job.L}`;
  if (htmlOnly) continue;
  if (!force && cache[cacheKey] === hash && existsSync(target)) {
    console.log(`= ${cacheKey} (cached)`);
    continue;
  }
  const master = join(WORK, 'masters', `${job.kind}-${job.id}.${job.L}.mp4`);
  mkdirSync(dirname(master), { recursive: true });
  console.log(`▶ ${cacheKey}`);
  const renderArgs = ['-y', HF, 'render', dir, '--quiet', '--fps', '24', '-o', master];
  if (job.bespoke) renderArgs.push('--variables-file', join(dir, `vars.${job.L}.json`), '--strict-variables');
  execFileSync('npx', renderArgs, { stdio: ['ignore', 'ignore', 'inherit'] });
  execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', master, '-vf', 'scale=960:540:flags=lanczos',
    '-c:v', 'libx264', '-preset', 'slow', '-tune', 'animation', '-crf', '27', '-r', '24', '-pix_fmt', 'yuv420p', '-movflags', '+faststart', '-an', target]);
  // Re-read before writing: parallel shards share this file.
  const latest = existsSync(cachePath) ? read(cachePath) : {};
  latest[cacheKey] = hash;
  writeFileSync(cachePath, JSON.stringify(latest, null, 2));
  done++;
  console.log(`✓ ${relative(ROOT, target)}`);
}

// ---------------------------------------------------------------------------
// Registry — every file on disk, so Metro bundles exactly what exists.
// ---------------------------------------------------------------------------
const entries = [];
for (const kind of ['lessons', 'drills']) {
  const dir = join(OUT, kind);
  if (!existsSync(dir)) continue;
  const byId = {};
  for (const f of readdirSync(dir).filter((f) => f.endsWith('.mp4')).sort()) {
    const m = f.match(/^(.+)\.(az|ru|en)\.mp4$/);
    if (!m) continue;
    (byId[m[1]] ??= {})[m[2]] = `../../assets/videos/${kind}/${f}`;
  }
  for (const [id, langs] of Object.entries(byId)) {
    if (!langs.az) continue;
    const prefix = kind === 'lessons' ? 'lesson' : 'drill';
    entries.push(`  '${prefix}:${id}': {\n${LANGS.filter((L) => langs[L]).map((L) => `    ${L}: require('${langs[L]}'),`).join('\n')}\n  },`);
  }
}
const registry = `// GENERATED by explainers/build.mjs — do not edit by hand.
import type { Locale } from '@/types/content';

/**
 * Every bundled video, keyed \`lesson:<id>\` / \`drill:<id>\`. Metro can only
 * bundle files it sees in a static \`require\`. A missing language falls back
 * to Azerbaijani, the same rule the text follows. Filmed footage dropped in
 * under the same filename replaces a rendered explainer.
 */
type Sources = Partial<Record<Locale, number>> & { az: number };

const VIDEO_FILES: Record<string, Sources> = {
${entries.join('\n')}
};

export function videoSource(key: string, locale: Locale): number | undefined {
  const entry = VIDEO_FILES[key];
  return entry ? entry[locale] ?? entry.az : undefined;
}
`;
writeFileSync(join(ROOT, 'src', 'content', 'videos.ts'), registry);
console.log(`\n${done} rendered, ${jobs.length} jobs, ${entries.length} items registered`);
